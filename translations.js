// Current language
let currentLanguage = localStorage.getItem('language') || 'en';

// Translation function
function t(key) {
    return translations[currentLanguage][key] || translations['en'][key] || key;
}

// Switch language function
function switchLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('language', lang);
    updatePageContent();
    
    // Update language switcher buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
    });
    document.querySelector(`[data-lang="${lang}"]`).classList.add('active');
}

// Update page content with current language
function updatePageContent() {
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
            if (element.type === 'submit' || element.type === 'button') {
                element.value = t(key);
            } else {
                element.placeholder = t(key);
            }
        } else {
            element.textContent = t(key);
        }
    });
    
    // Update select options
    updateSelectOptions();
}

// Update select options
function updateSelectOptions() {
    // Specialization select
    const specializationSelect = document.getElementById('specialization');
    if (specializationSelect) {
        const options = specializationSelect.querySelectorAll('option');
        options.forEach(option => {
            const key = option.getAttribute('data-translate');
            if (key) {
                option.textContent = t(key);
            }
        });
    }
    
    // Time slot select
    const timeSlotSelect = document.getElementById('time-slot');
    if (timeSlotSelect) {
        const options = timeSlotSelect.querySelectorAll('option');
        options.forEach(option => {
            const key = option.getAttribute('data-translate');
            if (key) {
                option.textContent = t(key);
            }
        });
    }
    
    // Duration select
    const durationSelect = document.getElementById('duration');
    if (durationSelect) {
        const options = durationSelect.querySelectorAll('option');
        options.forEach(option => {
            const key = option.getAttribute('data-translate');
            if (key) {
                option.textContent = t(key);
            }
        });
    }
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', function() {
    // Set initial language button state
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
    });
    const currentBtn = document.querySelector(`[data-lang="${currentLanguage}"]`);
    if (currentBtn) {
        currentBtn.classList.add('active');
    }
    
    // Update content
    updatePageContent();
});